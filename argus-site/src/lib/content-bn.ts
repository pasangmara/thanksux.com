/* ---------- line breaking ----------
   Bangla lines should never break inside "টি-শার্ট", between a number and its unit
   ("৩০ দিন"), or inside short fixed phrases ("এআই চ্যাটবট", "SEE অডিট"), and never end on "ও". */
const NBH = "\u2011"; // non-breaking hyphen
const NBSP = "\u00a0";
const BN_CHAR = "\u0980-\u09FF";
const tidy = (t: string) =>
  t
    .replace(new RegExp(`([${BN_CHAR}A-Za-z0-9])-([${BN_CHAR}])`, "g"), `$1${NBH}$2`)
    .replace(new RegExp(`([${BN_CHAR}])-([A-Za-z0-9])`, "g"), `$1${NBH}$2`)
    .replace(/([০-৯]+) (দিন|দিনে|দিনের|মাস|মাসে|মাসের|মিনিট|মিনিটের|ঘণ্টা|ঘণ্টার|বছর|বছরের|সেকেন্ডে|বার|টি)/g, `$1${NBSP}$2`)
    .replace(/(এআই|SEE|ফেসবুক|হোয়াটসঅ্যাপ) (?=[^\s—])/g, `$1${NBSP}`)
    // "ও" / "আর" (and) stay with the word after them instead of ending a line.
    .replace(/ (ও|আর) /g, ` $1${NBSP}`);

/** Applies tidy() to every string (and every string a text function returns) in the content. */
function tidyDeep<T>(v: T): T {
  if (typeof v === "string") return tidy(v) as T;
  if (typeof v === "function") return ((...args: unknown[]) => tidyDeep((v as (...a: unknown[]) => unknown)(...args))) as T;
  if (Array.isArray(v)) return v.map(tidyDeep) as T;
  if (v && typeof v === "object") {
    return Object.fromEntries(
      Object.entries(v).map(([k, x]) => [k, KEEP.has(k) ? x : tidyDeep(x)]),
    ) as T;
  }
  return v;
}
// Identifiers and links are left exactly as they are.
const KEEP = new Set(["id", "code", "href", "lang", "pillar", "n"]);

const pick = <T,>(map: Record<string, T>, key: string) => {
  const v = map[key];
  if (!v) throw new Error(`Missing Bangla text for ${key}`);
  return v;
};

