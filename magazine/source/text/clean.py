def rule_fix(t, aggressive=True):
    t = unicodedata.normalize('NFC', t)
    # য় / ড় / ঢ় may come decomposed
    t = t.replace('য়', 'য়').replace('ড়', 'ড়').replace('ঢ়', 'ঢ়')
    # OCR artefacts for য়
    t = t.replace('য্' + ZWNJ, 'য়').replace('ষ্' + ZWNJ, 'য়').replace('ঘ্' + ZWNJ, 'য়')
    t = t.replace('যূ', 'য়').replace('ষ্া', 'য়া').replace('যৃ', 'য়')
    t = re.sub('য্(?=[\\s।,;:!?\\-—\'"”“)\\]]|$)', 'য়', t)
    t = re.sub('ষ্(?=[\\s।,;:!?)\\]]|$)', 'য়', t)
    t = re.sub('য্(?=[' + VS + CONS + '])', 'য়', t)
    t = re.sub('ষ্(?=[' + VS + 'রট])', lambda m: m.group(0), t)  # keep ষ্ট etc.
    t = t.replace(ZWNJ, '')
    # mid-word য -> য় (except known legit roots)
    keep = ('যোগ', 'যুক্ত', 'যথা', 'যুগ', 'যাত্রা', 'যায়ী', 'যাযী', 'যান', 'যোজন', 'যাপন', 'যোগ্য')
    def mid_y(m):
        word = m.group(0)
        out = []
        for i, ch in enumerate(word):
            if ch == 'য' and i > 0 and word[i-1] != '্' and word[i+1:i+2] != '\u09bc' and not any(word[i:i+len(k)] == k for k in keep):
                out.append('য়')
            else:
                out.append(ch)
        return ''.join(out)
    t = re.sub('[ঀ-৿]+', mid_y, t)
    # ষ misread as য় in common suffixes
    t = re.sub('িষে', 'িয়ে', t); t = re.sub('েষে', 'েয়ে', t)
    t = re.sub('ওষা', 'ওয়া', t); t = re.sub('ওষ্', 'ওয়', t)
    t = re.sub('ষ্(?=[ছ])', 'য়', t)
    t = t.replace('\u09bc\u09bc', '\u09bc')
    t = re.sub('(?<!বা)(?<!আ)(?<!না)য়ু', 'য়', t)
    t = t.replace('৪ ', ': ') if False else t
    return t

