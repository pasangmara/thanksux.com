def word_fix(t):
    def rep(m):
        w = m.group(0)
        return WORDS.get(w, w)
    return re.sub('[ঀ-৿‌‍]+', rep, t)

def clean(t, aggressive=True):
    t = rule_fix(t, aggressive)
    t = word_fix(t)
    t = re.sub('[ \t]+', ' ', t)
    t = t.replace(' ।', '।').replace(' ,', ',')
    return t

