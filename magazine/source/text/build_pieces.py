def fx(s):
    for a, b in FIX: s = s.replace(a, b)
    s = s.replace('*', '').strip()
    s = re.sub(r'\s+', ' ', s)
    s = re.sub(r'"([^"]+)"', r'“\1”', s)
    s = s.replace(' ।', '।').replace(' ,', ',')
    if s and s[-1] not in '।?!”"…:–—)' and not s.endswith('...'): s += '।'
    return s

